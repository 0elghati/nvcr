#!/usr/bin/env python3
"""Generate NVCR's DCVC-UF glue kernels from pinned upstream CUDA sources (C8 phase 3).

Copies every __global__ and __device__ function from upstream's elementwise
kernel files into src/dcvcuf/backend/tensorrt/glue_kernels.inc. The only
change is the half type (at::Half -> Half, NVCR's c10-equivalent type), so the
device arithmetic stays upstream's. Host wrappers taking at::Tensor are not
copied; NVCR's launchers replace them. --check verifies the committed file
matches a regeneration from the pinned checkout.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys

PINNED_REFERENCE_COMMIT = "cbdae87a5445114cdc7f48816da63ea80bdeac40"
SOURCES = (
    "src/layers/extensions/inference/elementwise/stream.cu",
    "src/layers/extensions/inference/elementwise/cat_and_pad.cu",
    "src/layers/extensions/inference/elementwise/shuffle.cu",
)
OUTPUT = Path(__file__).resolve().parents[3] / "src/dcvcuf/backend/tensorrt/glue_kernels.inc"


def verify_reference(root):
    commit = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"],
                                     text=True).strip()
    if commit != PINNED_REFERENCE_COMMIT:
        raise ValueError(f"expected upstream {PINNED_REFERENCE_COMMIT}, found {commit}")
    status = subprocess.check_output(
        ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=no"], text=True)
    if status.strip():
        raise ValueError("reference sources must be unmodified")


def device_functions(text):
    """Yields top-level functions whose signature is __global__ or __device__."""
    lines = text.split("\n")
    index = 0
    while index < len(lines):
        line = lines[index]
        if not (line.startswith("template") or line.startswith("__global__")
                or line.startswith("__forceinline__")):
            index += 1
            continue
        start = index
        depth = 0
        opened = False
        body = []
        while index < len(lines):
            body.append(lines[index])
            depth += lines[index].count("{") - lines[index].count("}")
            opened = opened or "{" in lines[index]
            index += 1
            if opened and depth == 0:
                break
        signature = "\n".join(body).split("{", 1)[0]
        if "__global__" in signature or "__device__" in signature:
            yield start, "\n".join(body)


def generate(root):
    parts = [
        "// Generated by scripts/backends/dcvcuf/port_glue_kernels.py from microsoft/DCVC",
        f"// {PINNED_REFERENCE_COMMIT} (MIT License, Copyright (c) Microsoft Corporation).",
        "// Device code is upstream's with at::Half renamed to Half; do not edit by hand.",
    ]
    for relative in SOURCES:
        source = (root / relative).read_text(encoding="utf-8")
        digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
        parts.append(f"\n// ---- {relative} (sha256 {digest})")
        for _start, function in device_functions(source):
            parts.append("")
            parts.append(re.sub(r"\bat::Half\b", "Half", function))
    return "\n".join(parts) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    verify_reference(args.reference_root)
    text = generate(args.reference_root)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} does not match the pinned upstream sources", file=sys.stderr)
            return 1
        print("glue kernels match pinned upstream")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
